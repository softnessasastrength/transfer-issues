"""Vercel serverless entrypoint for the Transit Atlas API.

This is a thin adapter, not a fork: every request is dispatched to
``server.handle`` — the exact function the local loopback server uses —
so the hosted API and the local API cannot drift apart. The only jobs
here are (1) making the project-root modules importable from the
function bundle, (2) recovering the original ``/api/v1/...`` path from
the ``atlas_path`` query parameter that the vercel.json rewrite injects,
and (3) mapping results and exceptions to HTTP exactly as
``server.Handler`` does.

The data directory (``data/atlas.sqlite`` + ``data/sources.json``) is
generated by the deploy build (``scripts/prepare_data.py``) and bundled
with the function via ``includeFiles`` in vercel.json. It is never
committed to Git; see DECISIONS.md (2026-11-14, Vercel deployment form).
"""
import json
import pathlib
import sys
from http.server import BaseHTTPRequestHandler
from urllib.parse import parse_qs, urlparse

# The atlas modules (server.py, database.py, routing.py, bubble.py) live
# at the project root; this file lives in api/. In the Vercel bundle the
# project structure is preserved, so the parent of this file's directory
# is the project root both locally and in the function.
ROOT = pathlib.Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import server as atlas_server  # noqa: E402

# Requests that reach the function without the rewrite (the bare
# function URL) are answered with the meta document: a useful, honest
# health check for verifying a deployment.
_ROOT_PATHS = {'', '/', '/api', '/api/', '/api/index', '/api/index.py'}


def resolve(path, query):
    """Map a request target to (api_path, params) for server.handle."""
    q = parse_qs(query)
    injected = q.pop('atlas_path', None)
    if injected:
        return injected[0], q
    if path in _ROOT_PATHS:
        return '/api/v1/meta', q
    return path, q


def dispatch(path, query):
    """Return (status, payload_dict) using server.handle's contract."""
    api_path, q = resolve(path, query)
    try:
        return 200, atlas_server.handle(api_path, q)
    except (ValueError, KeyError) as e:
        return 400, {'error': str(e)}
    except LookupError as e:
        return 404, {'error': str(e)}
    except Exception:
        import traceback
        traceback.print_exc()
        return 500, {'error': 'Server error; see deployment logs'}


class handler(BaseHTTPRequestHandler):
    """Vercel Python runtime entrypoint (class must live in this file)."""

    def do_GET(self):
        parsed = urlparse(self.path)
        status, payload = dispatch(parsed.path, parsed.query)
        data = json.dumps(payload, separators=(',', ':')).encode()
        self.send_response(status)
        self.send_header('Content-Type', 'application/json')
        self.send_header('Cache-Control', 'no-store')
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('Content-Length', str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def _method_not_allowed(self):
        data = b'{"error":"Method not allowed; the atlas API is read-only"}'
        self.send_response(405)
        self.send_header('Content-Type', 'application/json')
        self.send_header('Cache-Control', 'no-store')
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('Content-Length', str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    do_POST = _method_not_allowed
    do_PUT = _method_not_allowed
    do_DELETE = _method_not_allowed
    do_PATCH = _method_not_allowed
